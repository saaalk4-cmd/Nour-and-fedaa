def makers():
    """قوائم «مصانع» الدروس حسب النوع؛ كل مصنع يأخذ رقم الأسبوع ويرجع درسًا."""
    L = [lambda w, i=i: letter(w, i) for i in range(len(LETTERS))]
    M = [lambda w, s=s, t=t, d=d: manners(w, PREFIX + s, t, t.split(' ')[-1], *d, flip=(w + len(s)) % 2 == 1)
         for s, t, d in MANNERS_MORE]
    V = []
    for k in range(max(len(VOCAB), len(COUNTS))):
        if k < len(VOCAB):
            s, t, e, p = VOCAB[k]
            V.append(lambda w, s=s, t=t, e=e, p=p: vocab(w, PREFIX + s, t, e, p))
        if k < len(COUNTS):
            s, t, e, o, n, nums = COUNTS[k]
            V.append(lambda w, s=s, t=t, e=e, o=o, n=n, nums=nums: counting(w, PREFIX + s, t, e, o, n, nums))
        if k < len(COLOR_SETS):
            s, t, e, items = COLOR_SETS[k]
            V.append(lambda w, s=s, t=t, e=e, items=items: colors_of(w, s, t, e, items))
        if k < len(OPPOSITES):
            s, t, e, p = OPPOSITES[k]
            V.append(lambda w, s=s, t=t, e=e, p=p: opposites(w, PREFIX + s, t, e, p))
    return L, M, V


def build():
    cur_path = os.path.join(ROOT, 'curriculum.json')
    cur = json.load(open(cur_path, encoding='utf-8'))
    for w in cur['weeks']:
        for d in w['days']:
            d['earlyLessons'] = [i for i in d.get('earlyLessons', [])
                                 if PREFIX not in i and i not in ANCHORS]
    L, M, V = makers()
    queues = {'A': list(ANCHORS), 'L': L, 'M': M, 'V': V}
    order = ['L', 'A', 'V', 'M']
    lessons = []
    turn = 0
    for w in [w for w in cur['weeks'] if w['week'] >= 9]:
        for d in w['days']:
            while len(d['earlyLessons']) < 3 and any(queues.values()):
                kind = order[turn % len(order)]
                turn += 1
                if not queues[kind]:
                    continue
                item = queues[kind].pop(0)
                if kind == 'A':
                    d['earlyLessons'].append(item)
                else:
                    lesson = item(w['week'])
                    for s in lesson['steps']:
                        s['say'] = s.get('say') or s['text']
                    lessons.append(lesson)
                    d['earlyLessons'].append(lesson['id'])
    left = {k: len(v) for k, v in queues.items() if v}
    save(FILE, lessons)
    json.dump(cur, open(cur_path, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
    print('nour more: %d new lessons, %d anchors placed, left over: %s' % (len(lessons), len(ANCHORS) - len(queues['A']), left))


if __name__ == '__main__':
    build()
