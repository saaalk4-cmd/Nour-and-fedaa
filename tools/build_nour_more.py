def colors_of(week, slug, title, emoji, items):
    steps = [(e, t, t) for e, t, _ in items[:2]]
    target = items[0][2]
    pool = [e for e, _, c in items if c != target] + ['🍇', '🌊', '🍌', '🥒', '🍎']
    qs = []
    for k, (e, _t, c) in enumerate(items[:2]):
        wrong = [x for x in pool if x != e][:2]
        opts, pos = three(e, wrong, k)
        qs.append(EQ('🎨', 'أين الشيء %s؟' % c.replace('ال', 'ال', 1), opts, pos, c, e, 'أحسنتِ! هذا لونه %s.' % c))
    return E(week, 'w%de_%scolor_%s' % (week, PREFIX, slug), 'لون %s' % title, emoji, 'learn', steps, qs,
             'أعرف الألوان في الأشياء حولي', 'أعرف لون %s.' % title.split(' ')[0])


