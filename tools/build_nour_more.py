def letter(week, i):
    ch, name, a, b = LETTERS[i]
    others = [LETTERS[(i + 5) % 28][2][0], LETTERS[(i + 11) % 28][3][0]]
    steps = [
        ('🔤', ch, 'هذا حرف %s' % name),
        (a[0], a[1], '%s، %s' % (ch, a[1])),
        (b[0], b[1], '%s، %s' % (ch, b[1])),
    ]
    o1, p1 = three(a[0], [b[0]] + others, i)
    o2, p2 = three(b[0], others, i + 1)
    qs = [
        EQ('❓', 'أين ال%s؟' % a[1] if not a[1].startswith('رجل') else 'أين %s؟' % a[1], o1, p1, a[1], a[0], 'أحسنتِ!'),
        EQ('🔤', 'أي صورة تبدأ بحرف %s؟' % name, o2, p2, b[1], b[0], 'أحسنتِ! %s تبدأ بحرف %s.' % (b[1], name)),
    ]
    return E(week, 'w%de_%sletter_%d' % (week, PREFIX, i + 1), 'حرف %s %s' % (name, a[0]), a[0], 'learn', steps, qs,
             'أسمع الحرف وأعرف صورًا تبدأ به', 'أعرف حرف %s.' % name)


