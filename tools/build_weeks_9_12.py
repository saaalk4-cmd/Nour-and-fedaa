def mixed_letters(week, id, letters, title='أراجع الحروف 🔤'):
    qs = []
    for i, letter in enumerate(letters):
        w, e = bw.WORDS[letter][i % 2]
        qs.append(Q('أي كلمة تبدأ بحرف %s؟' % letter, w, others(letter, 2, i * 3 + week), i + week,
                    'اسمعي أول الصوت في الكلمة', e))
    return L(week, id, title, '🔤', 'learn', [('🔤', 'هيا نراجع حروفنا!', None)], qs,
             'أراجع الحروف', 'أتذكّر حروفي.')


def read_word(week, id, title, emoji, words):
    """قراءة مبكرة: نجمع الحروف لنقرأ كلمة. words: [(الكلمة، الحروف مفصولة، صورة)]"""
    steps = [(e, '%s هي: %s' % (w, parts), None) for w, parts, e in words]
    qs = []
    for k, (w, parts, e) in enumerate(words):
        wrong = [x[0] for x in words if x[0] != w][:2]
        qs.append(Q('أي كلمة تعني %s؟' % e, w, wrong, k, 'اسمعي الحروف ثم الكلمة', e))
    return L(week, id, title, emoji, 'learn', steps, qs, 'أقرأ كلمات بسيطة', 'أجمع الحروف لأقرأ كلمة.')


def numbers_lesson(week, id, title, pairs):
    steps = [('🔢', '%d = %s' % (n, name), None) for n, name in pairs]
    qs = []
    for k, (n, name) in enumerate(pairs[:3]):
        wrong = [str(m) for m, _ in pairs if m != n][:2]
        qs.append(Q('ما العدد %s؟' % name, str(n), wrong, k, 'اسمعي اسم العدد', '🔢'))
    return L(week, id, title, '🔢', 'learn', steps, qs, 'أعرف الأعداد الكبيرة', 'أعدّ حتى 20.')


def O(prompt, items, hint, emoji=None, praise=None):
    """سؤال ترتيب: items بالترتيب الصحيح؛ التطبيق يعرضها بترتيب آخر."""
    q = {'prompt': prompt, 'options': list(items), 'answerIndex': 0, 'hint': hint, 'kind': 'order'}
    if emoji:
        q['emoji'] = emoji
    if praise:
        q['praise'] = praise
    return q


