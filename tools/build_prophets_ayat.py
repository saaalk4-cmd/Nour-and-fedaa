# حروف التشكيل والعلامات القرآنية: تُزال فقط للتحقق من وجود الاسم.
_MARKS = re.compile('[ؐ-ًؚ-ٰٟۖ-ۭ]')


def skeleton(t):
    t = _MARKS.sub('', t).replace('ٱ', 'ا').replace('ـ', '')
    return re.sub('[أإآ]', 'ا', t)


def load_tanzil(path):
    q = {}
    with open(path, encoding='utf-8') as fh:
        for line in fh:
            p = line.rstrip('\n').split('|')
            if len(p) != 3 or not p[0].isdigit():
                continue
            # ۞ علامة ربع الحزب في المصحف وليست من لفظ الآية.
            s, a, t = int(p[0]), int(p[1]), p[2].replace('ـ', '').replace('۞ ', '').replace('۞', '')
            if a == 1 and s not in (1, 9) and t.startswith('بِسْمِ'):
                t = ' '.join(t.split(' ')[4:])  # البسملة المضافة ليست آية من السورة
            q[(s, a)] = t
    assert len(q) == 6236, len(q)
    return q


def main():
    q = load_tanzil(sys.argv[1])
    names = {c['number']: c['name'].replace('سُورَةُ ', '') for c in json.load(open(sys.argv[2], encoding='utf-8'))['data']}
    out = []
    for (pid, who, title, emoji, s, a, b, meaning, word, say, group, name_in_ayah) in ITEMS:
        text = ' '.join(q[(s, v)] for v in range(a, b + 1))
        if name_in_ayah is not None:
            assert skeleton(name_in_ayah) in skeleton(text), (pid, text)
        out.append({'id': pid, 'prophet': who, 'title': title, 'emoji': emoji,
                    'surahNumber': s, 'surahName': surah_name(names[s]), 'ayahFrom': a, 'ayahTo': b,
                    'text': text, 'kidMeaning': meaning,
                    'toddlerWord': word, 'toddlerSay': say, 'meaningGroup': group})
    doc = {'schema': 1,
           'source': {'type': 'quran', 'name': 'Tanzil Quran Text (Uthmani)',
                      'url': 'https://tanzil.net/docs/text_license',
                      'license': 'CC BY 3.0 — verbatim copying only'},
           'verses': out}
    path = os.path.join(os.path.dirname(__file__), '..', 'assets', 'content', 'prophets_ayat.json')
    with open(path, 'w', encoding='utf-8') as fh:
        json.dump(doc, fh, ensure_ascii=False, indent=2)
    print(len(out), 'prophets')


# أسماء السور بلا تشكيل (كما في بقية التطبيق)
def surah_name(n):
    n = re.sub('[\\u064B-\\u065F\\u0670\\u06D6-\\u06ED]', '', n).replace('\u0671', '\u0627').strip()
    return {'\u0633\u0628\u0625': '\u0633\u0628\u0623'}.get(n, n)


if __name__ == '__main__':
    main()
