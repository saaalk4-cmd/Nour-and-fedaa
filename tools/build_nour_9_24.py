def three(correct, wrong_pool, k):
    """خيارات صور: الصحيح + اثنان غيره، ويتغيّر موضع الصحيح مع k."""
    wr = []
    for w in list(wrong_pool) + POOL:
        if w != correct and w not in wr:
            wr.append(w)
        if len(wr) == 2:
            break
    opts = wr[:]
    pos = k % 3
    opts.insert(pos, correct)
    return opts, pos


