def build_nour():
    b1324.build()
    spec = week_spec()
    cur_path = os.path.join(ROOT, 'curriculum.json')
    cur = json.load(open(cur_path, encoding='utf-8'))
    by_week = {w['week']: w for w in cur['weeks']}
    for wk, (_title, vlist, mlist, anchor1, anchor2) in spec.items():
        lessons = []
        v_ids, picks = [], []
        for item in vlist:
            kind = item[0]
            slug, title, emoji = item[1], item[2], item[3]
            if kind == 'vocab':
                lessons.append(vocab(wk, slug, title, emoji, item[4]))
                picks.append((item[4][0][0], item[4][0][1], [e for e, _ in item[4]]))
            elif kind == 'sounds':
                lessons.append(sounds(wk, slug, title, emoji, item[4]))
                picks.append((item[4][1][0], item[4][1][1], [e for e, _, _ in item[4]]))
            elif kind == 'count':
                lessons.append(counting(wk, slug, title, emoji, item[4], item[5], item[6]))
            elif kind == 'opp':
                lessons.append(opposites(wk, slug, title, emoji, item[4]))
            v_ids.append(lessons[-1]['id'])
        m_ids = []
        for j, (mslug, mtitle) in enumerate(mlist):
            scene, scene_say, q_say, good, bad, hint, praise = MANNERS[mslug]
            lessons.append(manners(wk, mslug, mtitle, mtitle.split(' ')[-1], scene, scene_say, q_say, good, bad,
                                   hint, praise, flip=(wk + j) % 2 == 1))
            m_ids.append(lessons[-1]['id'])
        lessons.append(review(wk, 'لعبة الأسبوع', picks[:3]))
        review_id = lessons[-1]['id']
        for l in lessons:
            for s in l['steps']:
                s['say'] = s.get('say') or s['text']
        save('week%d_early_lessons.json' % wk, lessons)

        days = by_week[wk]['days']
        plan = [
            ([anchor1] if anchor1 else []) + [v_ids[0]],
            [v_ids[1], m_ids[0]],
            [v_ids[2]] if len(v_ids) > 2 else [],
            [m_ids[1]] + ([anchor2] if anchor2 else []),
            [review_id],
        ]
        for d, ids in zip(days, plan):
            d['earlyLessons'] = ids
    json.dump(cur, open(cur_path, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
    print('nour weeks 9-24 built')


if __name__ == '__main__':
    build_nour()
