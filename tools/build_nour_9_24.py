def vocab(week, slug, title, emoji, pairs, n=3):
    """pairs = [(emoji, 'الكلمة')]. الأسئلة: «أين ...؟» باختيار صورة."""
    steps = [(e, w, w) for e, w in pairs]
    qs = []
    others = [e for e, _ in pairs]
    for k in range(min(n, len(pairs))):
        e, w = pairs[(k * 2 + 1) % len(pairs)] if k else pairs[0]
        opts, pos = three(e, others, k)
        qs.append(EQ('❓', 'أين %s؟' % w, opts, pos, w, e, 'أحسنتِ!'))
    return E(week, 'w%de_%s' % (week, slug), title, emoji, 'learn', steps, qs,
             'أتعرّف على الصور وأسمّيها', 'أعرف أسماء الأشياء من حولي.')


def sounds(week, slug, title, emoji, trip):
    """trip = [(emoji, 'الكلب', 'هو هو')]."""
    steps = [(e, w, '%s يقول %s' % (w, s)) for e, w, s in trip]
    qs = []
    others = [e for e, _, _ in trip]
    for k, (e, w, s) in enumerate(trip[:3]):
        opts, pos = three(e, others, k)
        qs.append(EQ('🔊', 'من يقول %s؟' % s, opts, pos, s, e, 'أحسنتِ! سمعتِ جيدًا.'))
    return E(week, 'w%de_%s' % (week, slug), title, emoji, 'learn', steps, qs,
             'أسمع الأصوات وأربطها بصاحبها', 'أعرف صوت كل حيوان.')


def counting(week, slug, title, emoji, obj, name, nums):
    """نعدّ مجموعات صغيرة: نختار المجموعة التي فيها العدد المطلوب."""
    steps = []
    for n in nums[:2]:
        steps.append((obj * n, '%d' % n, '، '.join(NUM[:n]) + ' ' + name))
    qs = []
    for k, n in enumerate(nums):
        bad = [m for m in (n - 1, n + 1, n + 2) if 1 <= m <= 10 and m != n][:2]
        groups = [obj * m for m in bad]
        pos = k % 3
        groups.insert(pos, obj * n)
        qs.append(EQ(obj * n, 'اضغطي على %s %s' % (NUM[n - 1], name), groups, pos, NUM[n - 1], obj,
                     'أحسنتِ! عددتِ صح.'))
    return E(week, 'w%de_%s' % (week, slug), title, emoji, 'learn', steps, qs,
             'أعدّ أشياء صغيرة', 'أعدّ بأصابعي وأعرف العدد.')


def opposites(week, slug, title, emoji, pairs):
    """pairs = [((emoji, 'كبير'), (emoji2, 'صغير'))]: نختار الصورة المناسبة للكلمة."""
    steps = []
    qs = []
    k = 0
    for (a, b) in pairs:
        steps.append((a[0], a[1], a[1]))
        steps.append((b[0], b[1], b[1]))
        for (x, y) in ((a, b), (b, a)):
            opts = [x[0], y[0]]
            pos = k % 2
            if pos == 1:
                opts = [y[0], x[0]]
            qs.append(EQ('❓', 'أين %s؟' % x[1], opts, pos, x[1], x[0], 'أحسنتِ!'))
            k += 1
    return E(week, 'w%de_%s' % (week, slug), title, emoji, 'learn', steps[:4], qs[:3],
             'أعرف الأضداد', 'أعرف الكبير والصغير وأمثالهما.')


def manners(week, slug, title, emoji, scene, scene_say, q_say, good, bad, hint, praise, flip=False):
    """موقف خلقي: صورتان (الجميلة / غيرها) واللمس على الجميلة."""
    opts = [bad, good] if flip else [good, bad]
    pos = 1 if flip else 0
    return E(week, 'w%de_%s' % (week, slug), title, emoji, 'akhlaq',
             [(scene, title.split(' ')[0] if False else scene_say, scene_say)],
             [EQ('%s ؟' % scene, q_say, opts, pos, hint, good, praise)],
             hint, hint + '.')


def review(week, title, picks):
    """لعبة نهاية الأسبوع: كل سؤال من إحدى مجموعات الأسبوع."""
    qs = []
    for k, (e, w, others) in enumerate(picks):
        opts, pos = three(e, others, k)
        qs.append(EQ('❓', 'أين %s؟' % w, opts, pos, w, e, 'أحسنتِ!'))
    return E(week, 'w%de_review_game' % week, 'لعبة الأسبوع 🎮', '🎮', 'learn',
             [('🎮', 'هيا نلعب', 'هيا نلعب بما تعلمنا!')], qs,
             'أراجع ما تعلمته', 'أنا أتعلم وألعب!')


