def eng_review(week, words):
    """مراجعة إنجليزي: كل الكلمات من جداول ENG."""
    all_pairs = {en: (ar, e) for _, _, ps in ENG.values() for en, ar, e in ps}
    qs = []
    for k, w in enumerate(words):
        ar, e = all_pairs[w]
        wrong = [v[0] for kk, v in all_pairs.items() if v[0] != ar]
        random.Random(week * 13 + k).shuffle(wrong)
        qs.append(Q('ماذا تعني %s؟' % w, ar, wrong[:2], k + week, 'تذكّري الصورة', e))
    return L(week, 'w%d_english_review' % week, 'أراجع الإنجليزي 🇬🇧', '🇬🇧', 'learn', [('🇬🇧', 'نراجع كلماتنا الإنجليزية.', None)], qs,
             'أراجع كلمات إنجليزية', 'أتذكّر كلمات إنجليزية.')


