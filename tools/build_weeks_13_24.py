def listen_lesson(week, id, surahs):
    steps = []
    for s in surahs:
        st = {'emoji': '🎧', 'text': 'استمعي لتلاوة سورة %s 🎧' % SURAH[s][0]}
        st['recite'] = [s, 1]
        steps.append(st)
    qs = []
    names = [SURAH[s][0] for s in SURAH]
    for k, s in enumerate(surahs):
        wrong = [n for n in names if n != SURAH[s][0]]
        random.Random(week * 100 + k).shuffle(wrong)
        q = Q('استمعي ثم اختاري: أي سورة سمعتِ؟', SURAH[s][0], wrong[:2], k, 'اضغطي على 🎧 لتسمعي مرة أخرى', '🎧')
        qs.append(R(q, s))
    n = SURAH[surahs[0]][1]
    qs.append(Q('كم آية في سورة %s؟' % SURAH[surahs[0]][0], str(n), [str(n + 1), str(n + 2)], 1,
                'عدّي الآيات التي سمعتِ', '📖'))
    lesson = L(week, id, 'أستمع للقرآن 🎧', '🎧', 'learn', [], qs,
               'أتعرّف على السور من تلاوتها', 'أتعرّف على بعض السور من صوتها.')
    lesson['steps'] = steps
    return lesson


def fin2(lessons):
    """مثل fin لكن يحترم الخطوات التي فيها recite (لا نطق آلي فوقها)."""
