def read_pic(week, id, title, words, seed):
    """اختاري الكلمة المناسبة للصورة (قراءة كلمات قصيرة)."""
    steps = [(READ[w], '%s' % w, None) for w in words[:3]]
    qs = []
    for k, w in enumerate(words):
        pool = [x for x in WL if x != w]
        random.Random(seed * 31 + k).shuffle(pool)
        qs.append(Q('ما الكلمة المناسبة للصورة؟', w, pool[:2], k + seed, 'اسمعي الكلمة ثم اختاري', READ[w]))
    return L(week, id, title, '📚', 'learn', steps, qs, 'أقرأ كلمة وأختار صورتها', 'أقرأ كلمات قصيرة وأعرف معناها.')


LET = ['ا', 'ب', 'ت', 'ج', 'ح', 'د', 'ر', 'ز', 'س', 'ش', 'ع', 'ف', 'ق', 'ك', 'ل', 'م', 'ن', 'ه', 'و', 'ي']


def first_letter_lesson(week, id, title, words, seed):
    """اختيار الحرف الأول من الكلمة."""
    steps = [(READ[w], '%s تبدأ بحرف %s' % (w, strip(w)[0] if strip(w)[0] != 'أ' else 'ا'), None) for w in words[:2]]
    qs = []
    for k, w in enumerate(words):
        first = strip(w)[0]
        first = {'أ': 'ا', 'إ': 'ا'}.get(first, first)
        pool = [x for x in LET if x != first]
        random.Random(seed * 17 + k).shuffle(pool)
        qs.append(Q('بأي حرف تبدأ كلمة %s؟' % READ[w], first, pool[:2], k + seed, 'انطقي الكلمة ببطء', READ[w]))
    return L(week, id, title, '🔠', 'learn', steps, qs, 'أختار الحرف الأول', 'أعرف بأي حرف تبدأ الكلمة.')


def build_word(week, id, words):
    """تكوين كلمة: ترتيب حروف مفصولة (حروف غير مكررة)."""
    qs = []
    for w, e in words:
        letters = [c for c in strip(w)]
        assert len(set(letters)) == len(letters) and 2 <= len(letters) <= 5, w
        qs.append(O('رتّبي الحروف لتكوني كلمة %s' % e, letters, 'ابدئي بأول صوت في الكلمة', e,
                    'أحسنتِ! كوّنتِ كلمة %s.' % w))
    return L(week, id, 'أكوّن كلمة 🧩', '🧩', 'learn', [('🧩', 'نجمع الحروف لنصنع كلمة.', None)], qs,
             'أكوّن كلمات بسيطة', 'أجمع الحروف لأكوّن كلمة.')


