def combo(week, id, title, items):
    """مهارات مدمجة: صورة + عدّ + قراءة كلمة + حرف أول. items: [(إيموجي، عدد، كلمة مشكّلة)]"""
    steps = [(e * n, '%d %s' % (n, w), None) for e, n, w in items[:2]]
    qs = []
    for k, (e, n, w) in enumerate(items):
        pool = [x for x in WL if x != w]
        random.Random(week * 7 + k).shuffle(pool)
        first = {'أ': 'ا', 'إ': 'ا'}.get(strip(w)[0], strip(w)[0])
        lp = [x for x in LET if x != first]
        random.Random(week * 5 + k).shuffle(lp)
        qs.append(Q('كم عدد هذه؟ %s' % (e * n), str(n), [str(n + 1), str(max(n - 1, 1))], k + week, 'عدّي ببطء', e))
        qs.append(Q('ما الكلمة المناسبة؟ %s' % e, w, pool[:2], k + 1, 'اسمعي الكلمة', e))
        qs.append(Q('بأي حرف تبدأ كلمة %s؟' % w, first, lp[:2], k + 2, 'انطقي الكلمة ببطء', e))
    return L(week, id, title, '🧠', 'learn', steps, qs[:5], 'أدمج العدّ والقراءة والحروف', 'أعدّ وأقرأ وأعرف الحروف معًا.')


