def M(prompt, pairs, hint, emoji=None, praise=None):
    """سؤال توصيل: pairs = [(يسار، يمين)]؛ التطبيق يعرض اليمين بترتيب مختلف."""
    q = {'prompt': prompt, 'options': ['%s|%s' % p for p in pairs], 'answerIndex': 0,
         'hint': hint, 'kind': 'match'}
    if emoji:
        q['emoji'] = emoji
    if praise:
        q['praise'] = praise
    return q


def R(q, surah, ayah=1):
    """يضيف تلاوة مسجّلة لسؤال أو خطوة (قاموس)."""
    q['recite'] = [surah, ayah]
    return q


