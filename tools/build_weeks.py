def others(letter, n=2, skip=0):
    pool = [w for k, ws in WORDS.items() if k != letter for w, _ in ws]
    pool = pool[skip % len(pool):] + pool[:skip % len(pool)]
    return pool[:n]


def letter_lesson(week, idx, letter):
    words = WORDS[letter]
    emoji = words[0][1]
    steps = [(e, '%s — تبدأ بحرف %s.' % (w, letter), None) for w, e in words]
    qs = []
    for j in range(2):
        w, e = words[j]
        qs.append(Q('أي كلمة تبدأ بحرف %s؟' % letter, w, others(letter, 2, idx * 3 + j * 5), idx + j,
                    'اسمعي أول الصوت في الكلمة', e))
    return L(week, 'w%d_letter_%d' % (week, idx), 'حرف %s %s' % (letter, emoji), emoji, 'learn', steps, qs,
             'أعرف حرف %s وصوته' % letter,
             'حرف %s في أول: %s.' % (letter, '، '.join(w for w, _ in words)))


def review_letters(week, letters):
    qs = []
    for i, letter in enumerate(letters):
        w, e = WORDS[letter][-1]
        qs.append(Q('أي كلمة تبدأ بحرف %s؟' % letter, w, others(letter, 2, i * 4 + week), i + week,
                    'تذكّري الكلمات التي تعلمناها', e))
    return L(week, 'w%d_review_letters' % week, 'أراجع الحروف 🔤', '🔤', 'learn',
             [('🔤', 'هيا نراجع حروفنا!', None)], qs, 'أراجع حروف الأسبوع', 'أتذكّر حروفي.')


# ---------------- الأرقام ----------------
def count_lesson(week, id, title, emoji, groups):
    """groups: قائمة أعداد؛ لكل عدد درس خطوة وسؤال."""
    steps, qs = [], []
    for k, n in enumerate(groups):
        steps.append((str(n) + '️⃣' if n < 10 else '🔟', '%s %s' % (AR[n], emoji * n), None))
        wrongs = [str(x) for x in (n - 1, n + 1) if x > 0]
        qs.append(Q('كم %s؟ %s' % (NAME[emoji], emoji * n), str(n), wrongs, k, 'عدّي ببطء بإصبعك', emoji))
    return L(week, id, title, emoji, 'learn', steps, qs, 'أعدّ حتى %d' % max(groups), 'أعدّ حتى %d.' % max(groups))


AR = {1: 'واحد', 2: 'اثنان', 3: 'ثلاثة', 4: 'أربعة', 5: 'خمسة', 6: 'ستة', 7: 'سبعة', 8: 'ثمانية',
      9: 'تسعة', 10: 'عشرة'}
NAME = {'🍎': 'تفاحة', '🌸': 'وردة', '⭐': 'نجمة', '🎈': 'بالونة', '🐟': 'سمكة', '🚗': 'سيارة', '🐦': 'عصفورًا'}


