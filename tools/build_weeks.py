def add_lesson(week, id, title, pairs):
    steps = [('➕', '%d + %d = %d' % (a, b, a + b), None) for a, b in pairs[:2]]
    qs = []
    for k, (a, b) in enumerate(pairs):
        qs.append(Q('%d + %d = ؟' % (a, b), str(a + b), [str(a + b + 1), str(max(a + b - 1, 0))] if a + b > 1 else ['3', '0'],
                    k, 'عدّي على أصابعك', '➕'))
    return L(week, id, title, '➕', 'learn', steps, qs, 'أجمع حتى 5', 'أجمع عددين صغيرين.')


