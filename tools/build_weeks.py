def save(name, lessons):
    with open(os.path.join(ROOT, name), 'w', encoding='utf-8') as f:
        json.dump({'schema': 1, 'lessons': lessons}, f, ensure_ascii=False, indent=2)


def src(week, early=False):
    ref = 'محتوى تعليمي أصلي — الأسبوع %d' % week
    return {'type': 'educational', 'reference': ref + (' (صور وصوت بلا قراءة)' if early else '')}


def opts(correct, wrongs, i):
    o = list(wrongs)
    o.insert(i % (len(o) + 1), correct)
    return o, i % (len(o))


def Q(prompt, correct, wrongs, i, hint, emoji=None, praise=None, say=None):
    options, ans = opts(correct, wrongs, i)
    q = {'prompt': prompt, 'options': options, 'answerIndex': ans, 'hint': hint}
    if emoji:
        q['emoji'] = emoji
    if praise:
        q['praise'] = praise
    if say:
        q['say'] = say
    return q


def L(week, id, title, emoji, cat, steps, qs, objective, learned, min_age=5, early=False):
    return {
        'id': id, 'title': title, 'emoji': emoji, 'category': cat,
        'minAge': min_age, 'maxAge': 4 if early else 6, 'difficulty': 1,
        'objective': objective, 'learned': learned, 'source': src(week, early),
        'steps': [dict(emoji=e, text=t, **({'say': s} if s else {})) for e, t, s in steps],
        'questions': qs,
    }


