# ---------------- علوم/إنجليزي ----------------
def science(week, id, title, emoji, steps, qs, obj, learned):
    return L(week, id, title, emoji, 'learn', steps, qs, obj, learned)


def english(week, id, title, emoji, pairs):
    steps = [(e, '%s = %s' % (en, ar), None) for en, ar, e in pairs]
    qs = []
    for k, (en, ar, e) in enumerate(pairs[:3]):
        wrong = [p[1] for p in pairs if p[1] != ar][:2]
        qs.append(Q('ماذا تعني %s؟' % en, ar, wrong, k, 'تذكّري الصورة', e))
    return L(week, id, title, emoji, 'learn', steps, qs, 'أتعلم كلمات إنجليزية جديدة',
             'مثل: %s = %s.' % (pairs[0][0], pairs[0][1]))


# ---------------- مواقف أخلاقية (تعليمية أصلية، بلا نسبة دينية) ----------------
def scenario(week, id, title, emoji, story, question, good, bad, hint, praise, learned, order):
    steps = [(emoji, s, None) for s in story]
    options = [good, bad] if order == 0 else [bad, good]
    return L(week, id, title, emoji, 'akhlaq', steps,
             [{'prompt': question, 'options': options, 'answerIndex': order and 1 or 0, 'hint': hint,
               'praise': praise, 'emoji': emoji}], learned, learned, min_age=4)


# ---------------- مسار نور (صور + صوت) ----------------
def E(week, id, title, emoji, cat, steps, qs, obj, learned, allow=False, source=None):
    d = L(week, id, title, emoji, cat, steps, qs, obj, learned, min_age=3, early=True)
    if source:
        d['source'] = source
    if allow:
        d['allowSpeech'] = True
    return d


def EQ(prompt, say, options, ans, hint, emoji=None, praise=None):
    q = {'prompt': prompt, 'say': say, 'options': options, 'answerIndex': ans, 'hint': hint}
    if emoji:
        q['emoji'] = emoji
    if praise:
        q['praise'] = praise
    return q


